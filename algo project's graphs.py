vertices = [50,200,400]

dijkstra_sparse = [0.00228,0.09100,0.60691]
dijkstra_dense = [0.00871,0.39332,3.16349]

floyd_sparse = [0.01090,0.51654,3.98705]
floyd_dense = [0.00792,0.47154,3.83911]

plt.figure(figsize=(8,5))

plt.plot(vertices,dijkstra_sparse,'o-',label='Dijkstra Sparse')
plt.plot(vertices,dijkstra_dense,'o-',label='Dijkstra Dense')
plt.plot(vertices,floyd_sparse,'s--',label='Floyd Sparse')
plt.plot(vertices,floyd_dense,'s--',label='Floyd Dense')

plt.title("Effect of Graph Density")
plt.xlabel("Number of Vertices")
plt.ylabel("Time (seconds)")
plt.grid(True)
plt.legend()

plt.tight_layout()
plt.show()