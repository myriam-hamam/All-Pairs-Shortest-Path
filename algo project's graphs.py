import matplotlib.pyplot as plt

labels = [
    "Small\nSparse",
    "Small\nDense",
    "Medium\nSparse",
    "Medium\nDense",
    "Large\nSparse",
    "Large\nDense"
]

dijkstra = [0.00228, 0.00871, 0.09100, 0.39332, 0.60691, 3.16349]
floyd = [0.01090, 0.00792, 0.51654, 0.47154, 3.98705, 3.83911]

# -------------------------
# Graph 1
# -------------------------

plt.figure(figsize=(10,5))
plt.plot(labels, dijkstra, marker='o', linewidth=2, label='Repeated Dijkstra')
plt.plot(labels, floyd, marker='s', linewidth=2, label='Floyd-Warshall')

plt.title("Execution Time Comparison")
plt.xlabel("Graph Type")
plt.ylabel("Time (seconds)")
plt.grid(True)
plt.legend()

plt.tight_layout()
plt.show()


